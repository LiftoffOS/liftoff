// Phase 0d — synthetic dataset generator for pre-cutover verification.
// Plan: "staging deployment exercised with a synthetic dataset
// (programmatically generated from seed distributions — no production
// PII). The generator lives at `tools/test-data-gen/` in each
// service's repo and produces: tenants, employees, plans,
// subscriptions, usage events, invoices, OAuth connectors — at
// volumes matching P95 of current production per type."
//
// For billing: tenants × plans × subscriptions × invoices × meter
// events. All PII-free — no real email addresses or names.

import { Pool } from 'pg';
import { randomUUID } from 'node:crypto';

interface GenOptions {
  pool: Pool;
  tenants: number;
  plans: number;
  invoicesPerTenant: number;
  meterEventsPerTenant: number;
}

const SYNTHETIC_VENDORS = ['anthropic', 'openai', 'internal'];
const SYNTHETIC_EVENT_TYPES = ['chat.tokens.input', 'chat.tokens.output', 'tool.invocation'];

export async function generate(opts: GenOptions): Promise<{
  tenants: number;
  plans: number;
  subscriptions: number;
  invoices: number;
  meterEvents: number;
}> {
  const client = await opts.pool.connect();
  try {
    await client.query('BEGIN');

    // Plans
    const planIds: string[] = [];
    for (let i = 0; i < opts.plans; i++) {
      const id = randomUUID();
      planIds.push(id);
      await client.query(
        `INSERT INTO plans (id, name, description, base_amount_cents, currency,
                            stripe_product_id, stripe_price_id, active)
         VALUES ($1, $2, $3, $4, 'USD', $5, $6, TRUE)`,
        [
          id,
          `Synthetic Plan ${i}`,
          `Plan generated by tools/test-data-gen/ — NOT for production`,
          String((i + 1) * 10_000n),
          `prod_synthetic_${i}`,
          `price_synthetic_${i}`,
        ],
      );
    }

    let totalSubscriptions = 0;
    let totalInvoices = 0;
    let totalMeterEvents = 0;

    for (let t = 0; t < opts.tenants; t++) {
      const tenantId = randomUUID();

      // 1 subscription per tenant (P95 pattern)
      const planId = planIds[Math.floor(Math.random() * planIds.length)];
      const now = Date.now();
      await client.query(
        `INSERT INTO subscriptions (id, tenant_id, stripe_subscription_id, status, plan_id,
                                    current_period_start, current_period_end, cancel_at_period_end)
         VALUES (gen_random_uuid(), $1, $2, 'active', $3, to_timestamp($4), to_timestamp($5), FALSE)`,
        [
          tenantId,
          `sub_synthetic_${tenantId}`,
          planId,
          Math.floor((now - 86_400_000 * 30) / 1000),
          Math.floor((now + 86_400_000 * 30) / 1000),
        ],
      );
      totalSubscriptions += 1;

      // Invoices
      for (let i = 0; i < opts.invoicesPerTenant; i++) {
        await client.query(
          `INSERT INTO invoices (id, tenant_id, stripe_invoice_id, status,
                                 amount_due_cents, amount_paid_cents, tax_cents,
                                 currency, period_start, period_end, issued_at, paid_at)
           VALUES (gen_random_uuid(), $1, $2, 'paid', $3, $3, 0,
                   'USD', to_timestamp($4), to_timestamp($5), to_timestamp($5), to_timestamp($5))`,
          [
            tenantId,
            `in_synthetic_${tenantId}_${i}`,
            String(10_000n + BigInt(i) * 500n),
            Math.floor((now - 86_400_000 * 30 * (i + 2)) / 1000),
            Math.floor((now - 86_400_000 * 30 * (i + 1)) / 1000),
          ],
        );
        totalInvoices += 1;
      }

      // Meter events
      for (let m = 0; m < opts.meterEventsPerTenant; m++) {
        const vendor = SYNTHETIC_VENDORS[m % SYNTHETIC_VENDORS.length];
        const evt = SYNTHETIC_EVENT_TYPES[m % SYNTHETIC_EVENT_TYPES.length];
        await client.query(
          `INSERT INTO meter_events (tenant_id, user_id, vendor, request_id, quantity, event_type, occurred_at, cost_micros)
           VALUES ($1, NULL, $2, $3, $4, $5, NOW() - (interval '1 second' * $6), $7)`,
          [
            tenantId,
            vendor,
            `req_synthetic_${tenantId}_${m}`,
            String(100n + BigInt(m) * 7n),
            evt,
            m * 60,
            String(100n * BigInt(m)),
          ],
        );
        totalMeterEvents += 1;
      }
    }

    await client.query('COMMIT');
    return {
      tenants: opts.tenants,
      plans: opts.plans,
      subscriptions: totalSubscriptions,
      invoices: totalInvoices,
      meterEvents: totalMeterEvents,
    };
  } catch (err) {
    try { await client.query('ROLLBACK'); } catch { /* ignore */ }
    throw err;
  } finally {
    client.release();
  }
}

if (process.argv[1]?.endsWith('test-data-gen/index.js')) {
  const { Pool: PgPool } = await import('pg');
  const pool = new PgPool({ connectionString: process.env.BILLING_DATABASE_URL });
  const result = await generate({
    pool,
    tenants: Number(process.env.SYNTH_TENANTS ?? '50'),
    plans: Number(process.env.SYNTH_PLANS ?? '5'),
    invoicesPerTenant: Number(process.env.SYNTH_INVOICES ?? '6'),
    meterEventsPerTenant: Number(process.env.SYNTH_METER_EVENTS ?? '2000'),
  });
  // eslint-disable-next-line no-console
  console.log(JSON.stringify(result, null, 2));
  await pool.end();
}
