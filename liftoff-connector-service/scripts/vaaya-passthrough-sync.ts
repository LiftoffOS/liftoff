// Vaaya pass-through map generation — which x402 endpoints the platform pays
// for through its Vaaya balance instead of its own x402 wallet.
//
//   npm run gen:vaaya-passthrough -- --catalog /path/to/vaaya-catalog.json
//
// Three of the platform's keyless x402 vendors are ALSO resold by Vaaya, which
// pays the merchant from a prepaid balance that auto-reloads. The platform's
// own x402 wallet does not auto-reload yet, so an endpoint Vaaya can serve is
// one the platform keeps serving after the wallet runs dry. That is the whole
// reason this map exists; it is a resilience lane, not a cheaper one (see
// src/clients/platform-x402-lane.ts for the measured price difference).
//
// The map is keyed by OUR OWN dispatch path, because that is what an executor
// holds when it has to decide who pays. An entry is written only when both
// sides carry the endpoint: a Vaaya row for something we do not serve is
// dropped, and an endpoint of ours Vaaya lacks is simply absent, which the
// lane reads as "the wallet pays for this one". Nothing here enables anything.
//
// The catalog file is the `GET https://vaaya.ai/api/catalog` body, dumped by a
// job that holds the key, so generation itself needs no credential and the
// result is reproducible from a file anyone can read and diff.

import * as fs from 'fs';
import * as path from 'path';
import { STRALE_DISPATCH } from '../src/catalog/generated/strale';
import { KADEC0_DISPATCH } from '../src/catalog/generated/kadec0';
import { GOOGLE_TRENDS_DISPATCH } from '../src/catalog/generated/google-trends';

interface CatalogRow {
  id?: string;
  service?: string;
  action?: string;
  endpoint?: string;
  method?: string;
  price_cents?: number;
}

/** Our path for an endpoint, spelled the way Vaaya spells it. Strale is the
 *  only vendor where the two disagree: we call its v2 surface, Vaaya resells
 *  the v1 slug of the same capability. */
const TO_VAAYA_ENDPOINT: Record<string, (ourPath: string) => string> = {
  strale: p => p.replace('/x402/v2/', '/x402/'),
  kadec0: p => p,
  google_trends: p => p,
};

/** The connector types this lane covers, and the paths each one serves.
 *  browserbase_x402 is deliberately absent: Vaaya resells Browserbase session
 *  lifecycle (create/extend/release/status) and we call /search and /fetch, so
 *  there is nothing to map and its calls stay on the wallet. */
const VENDORS: ReadonlyArray<{ connectorType: string; vaayaService: string; ourPaths: string[] }> = [
  { connectorType: 'strale',        vaayaService: 'strale',        ourPaths: Object.values(STRALE_DISPATCH).map(d => d.path) },
  { connectorType: 'kadec0',        vaayaService: 'kadec0',        ourPaths: Object.values(KADEC0_DISPATCH).map(d => d.path) },
  { connectorType: 'google_trends', vaayaService: 'google-trends', ourPaths: Object.values(GOOGLE_TRENDS_DISPATCH).map(d => d.path) },
];

function main(): void {
  const catalogFlag = process.argv.indexOf('--catalog');
  if (catalogFlag < 0 || !process.argv[catalogFlag + 1]) {
    console.error('usage: npm run gen:vaaya-passthrough -- --catalog <vaaya-catalog.json>');
    process.exit(1);
  }
  const body = JSON.parse(fs.readFileSync(process.argv[catalogFlag + 1], 'utf8')) as { rows?: CatalogRow[] };
  const rows = body.rows ?? [];
  if (rows.length === 0) throw new Error('vaaya catalog carries no rows — refusing to render an empty map');

  const lines: string[] = [];
  const counts: string[] = [];
  for (const vendor of VENDORS) {
    const theirs = new Map<string, CatalogRow>();
    for (const row of rows) {
      if (row.service !== vendor.vaayaService || !row.endpoint || !row.action) continue;
      theirs.set(row.endpoint, row);
    }
    const spell = TO_VAAYA_ENDPOINT[vendor.connectorType];
    const entries: string[] = [];
    for (const ourPath of [...new Set(vendor.ourPaths)].sort()) {
      const row = theirs.get(spell(ourPath));
      if (!row) continue;
      const cents = typeof row.price_cents === 'number' && row.price_cents >= 0 ? row.price_cents : null;
      entries.push(
        `    ${JSON.stringify(ourPath)}: { action: ${JSON.stringify(`${row.service}/${row.action}`)}, ` +
          `endpoint: ${JSON.stringify(row.endpoint)}, priceCents: ${cents ?? 'null'} },`,
      );
    }
    counts.push(`${vendor.connectorType} ${entries.length}/${new Set(vendor.ourPaths).size}`);
    lines.push(`  ${vendor.connectorType}: {`, ...entries, '  },');
  }

  const out = [
    '// GENERATED by scripts/vaaya-passthrough-sync.ts — do not edit by hand.',
    '//',
    '// Which of our own x402 endpoints the platform can also reach through its',
    '// Vaaya balance, keyed by the path our dispatch map holds. Absence means the',
    '// platform x402 wallet is the only funder for that endpoint.',
    '//',
    `// Coverage at generation: ${counts.join(', ')}.`,
    '',
    'export interface VaayaPassThrough {',
    '  /** `{service}/{action}` — the path segment of POST vaaya.ai/api/run/… */',
    '  action: string;',
    "  /** The upstream path Vaaya's meta-action takes as a parameter. */",
    '  endpoint: string;',
    "  /** Vaaya's listed price, or null where it quotes per call. */",
    '  priceCents: number | null;',
    '}',
    '',
    'export const VAAYA_PASSTHROUGH: Record<string, Record<string, VaayaPassThrough>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');

  const dest = path.join(__dirname, '..', 'src', 'catalog', 'generated', 'vaaya-passthrough.ts');
  fs.writeFileSync(dest, out);
  console.log(`wrote ${dest}\ncoverage: ${counts.join(', ')}`);
}

main();
