-- Let an archived agent actually be purged.
--
-- When the control plane deletes an AI team, this service receives
-- tenant.internal_agent.deleted and sets the agent's lifecycle to ARCHIVED.
-- Nothing ever removed the row, and the row is not a cache pointer: it holds
-- system_prompt, user_instructions, instructions_md, role, workflow_steps and
-- memory_scope. The agent's learned context survived too, because
-- memories.agent_id is ON DELETE SET NULL - so even a hard delete would have
-- kept every memory's content and merely forgotten whose it was.
--
-- The purge pass added alongside this migration deletes the memories
-- explicitly and then the agent, and thirteen foreign keys would abort that
-- DELETE: they reference agents(id) with no ON DELETE action, which is NO
-- ACTION and therefore a block rather than a cascade.
--
-- Eleven become CASCADE because they are the agent's own work: its workflows,
-- tasks, handoffs, escalations, actions, instructions, child tasks, policy
-- denials, reflection suggestions and the human feedback left on them.
--
-- The two audit tables stay as they are and become SET NULL instead: an audit
-- row outliving the thing it describes is the point of an audit row, and once
-- the reference is null it holds no agent content. That matches the control
-- plane's agent_audit_logs, which already had ON DELETE SET NULL.
--
-- Idempotent and name-agnostic: constraint names here were generated by
-- Postgres years ago and may differ between a migrated database and a rebuilt
-- one, so each is found in the catalog by (table, column, referenced table).

DO $$
DECLARE
  target   RECORD;
  con_name TEXT;
  want     CHAR(1);
BEGIN
  FOR target IN
    SELECT * FROM (VALUES
      -- the agent's own work: goes with it
      ('workflows',              'agent_id',      'c'),
      ('workflow_tasks',         'agent_id',      'c'),
      ('workflow_handoffs',      'from_agent_id', 'c'),
      ('workflow_handoffs',      'to_agent_id',   'c'),
      ('workflow_escalations',   'agent_id',      'c'),
      ('actions',                'agent_id',      'c'),
      ('reflection_suggestions', 'agent_id',      'c'),
      ('human_feedback',         'agent_id',      'c'),
      ('policy_denials',         'agent_id',      'c'),
      ('instructions',           'agent_id',      'c'),
      ('child_tasks',            'agent_id',      'c'),
      -- agent_audit_log is a CASCADE rather than a SET NULL for two reasons.
      -- Its agent_id is NOT NULL, so SET NULL is a constraint Postgres lets
      -- you declare and then fails on at delete time - a latent break rather
      -- than an error now. And it is a field-level change log: (field,
      -- old_value, new_value) over the agent's own columns, so its rows hold
      -- the prompt text this purge exists to remove.
      ('agent_audit_log',        'agent_id',      'c'),
      -- audit_logs records what was DONE, not what the agent was, and its
      -- column is nullable. The row outlives the agent with the link nulled.
      ('audit_logs',             'ai_team_id',    'n')
    ) AS t(tbl, col, action)
  LOOP
    want := target.action;

    IF to_regclass(target.tbl) IS NULL THEN
      RAISE NOTICE 'purge-cascade: % absent, skipping', target.tbl;
      CONTINUE;
    END IF;

    SELECT con.conname INTO con_name
      FROM pg_constraint con
      JOIN pg_class child  ON child.oid  = con.conrelid
      JOIN pg_class parent ON parent.oid = con.confrelid
      JOIN pg_attribute att ON att.attrelid = con.conrelid
                           AND att.attnum = con.conkey[1]
     WHERE con.contype = 'f'
       AND child.relname  = target.tbl
       AND parent.relname = 'agents'
       AND att.attname    = target.col
       AND array_length(con.conkey, 1) = 1
     LIMIT 1;

    IF con_name IS NULL THEN
      RAISE NOTICE 'purge-cascade: no single-column FK on %.% -> agents, skipping',
        target.tbl, target.col;
      CONTINUE;
    END IF;

    -- Already what we want? Leave it, so a re-run changes nothing.
    IF EXISTS (
      SELECT 1 FROM pg_constraint
       WHERE conname = con_name
         AND conrelid = to_regclass(target.tbl)
         AND confdeltype = want
    ) THEN
      CONTINUE;
    END IF;

    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', target.tbl, con_name);
    EXECUTE format(
      'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES agents(id) ON DELETE %s',
      target.tbl, con_name, target.col,
      CASE want WHEN 'c' THEN 'CASCADE' ELSE 'SET NULL' END
    );
    RAISE NOTICE 'purge-cascade: %.% now ON DELETE %', target.tbl, target.col,
      CASE want WHEN 'c' THEN 'CASCADE' ELSE 'SET NULL' END;
  END LOOP;
END $$;
