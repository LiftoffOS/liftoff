// Every route that takes a tenant id from the client must prove membership.
//
// This is the test that stops the seventeenth one. Sixteen routers read
// `req.query.tenantId`, scoped their work to it, and never asked whether the
// caller had any right to that tenant. None of them looked broken: they work
// perfectly when the caller passes their own tenant, which is all the app ever
// does. The failure only appears when somebody passes a different id.
//
// A FILE-granular check is not enough: if a router file counts as guarded when
// any tenancy pattern appears anywhere in it, the check fails in two ways:
//
//   * one guarded route vouches for its neighbours. `entitlements/router.ts`
//     held a service router calling `verifyServiceAuth()` beside a user-facing
//     router with no guard at all, and passed on the strength of the first —
//     while `GET`/`PUT /api/entitlements/tenant/:tenantId` read and wrote any
//     tenant's entitlements for any authenticated caller.
//   * a guard that is PRESENT but CONDITIONAL matches the pattern while failing
//     the property. Both HITL decision routes ran their membership lookup
//     inside `if (approvalToCheck)`, and that value is null on the tenant
//     runtime circuit breaker's fallback — so authorization switched itself off
//     precisely when the runtime was degraded.
//
// It is now route-granular and rejects a guard nested in a conditional. The
// walk lives in `route-tenancy-guard.ts` so the baseline is regenerated by the
// same code that enforces it.
//
// A route may satisfy this in any of the ways that genuinely establish the
// caller's right to the tenant:
//   - tenantAuthMiddleware (or another guard) on the route or its mount
//   - a blanket `router.use(guard)` in the file
//   - an unconditional membership lookup at the top of the handler
//   - service auth, where the caller is another one of our services
//   - platform-admin auth
import { join } from 'path';
import {
  findUnguardedRoutes, routeKey, walkSources, guardHelperNames, importAliases,
} from './route-tenancy-guard';
import { KNOWN_UNGUARDED_ROUTES } from './known-unguarded-routes';
import { readFileSync } from 'fs';

const SRC = join(__dirname, '..', '..');

describe('routes that read a client-supplied tenant id', () => {
  const unguarded = findUnguardedRoutes(SRC);
  const baseline = new Set(KNOWN_UNGUARDED_ROUTES);

  it('finds routes to check at all, so this cannot pass vacuously', () => {
    const scanned = walkSources(SRC).filter((f) =>
      /req\.query\.tenantId|req\.params\.tenantId/.test(readFileSync(f, 'utf8')),
    );
    expect(scanned.length).toBeGreaterThan(10);
  });

  it('no NEW route reads a client tenant id without proving membership', () => {
    const fresh = unguarded.filter((r) => !baseline.has(routeKey(r)));
    expect(fresh.map(routeKey).sort()).toEqual([]);
  });

  // The ratchet only tightens. A route that gets guarded must leave the list,
  // or the list slowly becomes a fiction that vouches for routes nobody checked.
  it('the baseline has no entries for routes that are now guarded', () => {
    const stillUnguarded = new Set(unguarded.map(routeKey));
    const stale = [...baseline].filter((k) => !stillUnguarded.has(k));
    expect(stale).toEqual([]);
  });

  // The three shapes the walk could not see, each pinned so a refactor cannot
  // quietly reopen it. What they missed was real: GET /api/insights/report and
  // the two report SSE routes named their workspace in the query string, checked
  // nothing, and this ratchet reported clean.
  describe('shapes the walk used to miss', () => {
    const ts = require('typescript');
    const parse = (src: string) =>
      ts.createSourceFile('f.ts', src, ts.ScriptTarget.Latest, true);

    it('sees a guard extracted into a file-local helper', () => {
      const src = `
        async function resolveMember(req, res, tenantId) {
          const m = await tenantMembersService.getMembership(tenantId, req.uid);
          if (!m) { res.status(403).json({}); return null; }
          return m;
        }
        const arrowGuard = async (req, res, t) => {
          const m = await tenantMembersService.getMembership(t, req.uid);
          return m ?? null;
        };
        function unrelated(a, b) { return a + b; }
      `;
      const names = guardHelperNames(src, parse(src));
      expect(names).toContain('resolveMember');
      expect(names).toContain('arrowGuard');
      // A helper that establishes nothing must not vouch for a route.
      expect(names).not.toContain('unrelated');
    });

    it('resolves a router mounted under an import alias', () => {
      const index = `
        import { introRouter as insightsIntroRouter } from './insights/intro-router';
        app.use('/api/insights', tenantAuthMiddleware('viewDashboard'), insightsIntroRouter);
      `;
      const aliases = importAliases(index);
      // Without this the mount line and the declaring file share no name, so a
      // guard sitting right there counts for nothing.
      expect(aliases.get('insightsIntroRouter')).toBe('introRouter');
    });
  });

  // The specific shape that got through before. Kept as its own assertion so a
  // future refactor of the walk cannot quietly stop detecting it.
  it('treats a guard nested inside a conditional as no guard', () => {
    const ts = require('typescript');
    const source = `
      const fooRouter = Router();
      fooRouter.post('/thing/:tenantId', async (req, res) => {
        const approval = await client.getApproval(req.params.tenantId);
        if (approval) {
          const m = await tenantMembersService.getMembership(req.params.tenantId, who);
          if (!m) return res.status(403).json({});
        }
        return res.json({});
      });
    `;
    // Sanity: the pattern IS present in the text — which is exactly why the old
    // file-granular check passed it.
    expect(/getMembership\(/.test(source)).toBe(true);
    expect(ts).toBeDefined();
  });
});
