// Internal notification fired on every new signup, to
// MAIL_SIGNUP_NOTIFICATION_ADDRESS. Returns null when that is unset, which is a
// supported configuration rather than a failure: the /signup-approval page is
// the surface that decides access, and an install with no operations mailbox
// should not have its signups mailed to an address out of the source.
// Renders the new user's First Name / Last Name / Email plus, unless they
// already have access via a whitelisted domain, an Approve (accent) and a
// Waitlist (outline) button. Both buttons open the authenticated
// /signup-approval page carrying a signed token; the `intent` query param
// pre-selects the action. reply-to is the signup's own email so hitting reply
// in the signups@ inbox writes straight to the user.
export async function sendSignupNotification(
  account: { firstName: string; lastName: string; email: string },
  opts: { pageUrl?: string; alreadyGranted: boolean },
): Promise<string | null> {
  const notifyTo = signupNotificationAddress();
  if (!notifyTo) return null;

  const firstName = account.firstName.trim() || '(not provided)';
  const lastName = account.lastName.trim() || '(not provided)';

  const rows: Array<[string, string]> = [
    ['First Name', firstName],
    ['Last Name', lastName],
    ['Email', account.email],
  ];
  const tableRows = rows
    .map(
      ([label, value]) =>
        `<tr><td style="padding:8px 12px;font-weight:bold;vertical-align:top;white-space:nowrap;">${label}</td><td style="padding:8px 12px;">${escapeHtml(value)}</td></tr>`,
    )
    .join('');
  const tableHtml = `<table style="border-collapse:collapse;width:100%;border:1px solid #e0e0e0;">${tableRows}</table>`;

  let body: string;
  if (opts.alreadyGranted) {
    body =
      buildParagraph(
        'Someone just signed up for Liftoff. They already have access because their email domain is on the allowed list, so no action is needed.',
      ) + tableHtml;
  } else if (opts.pageUrl) {
    const approveUrl = `${opts.pageUrl}&intent=approve`;
    const waitlistUrl = `${opts.pageUrl}&intent=waitlist`;
    body =
      buildParagraph(
        'Someone just signed up for Liftoff. Review their details below and choose whether to approve access or keep them on the waitlist.',
      ) +
      tableHtml +
      buildCTA('Approve', approveUrl) +
      buildOutlineButton('Waitlist', waitlistUrl) +
      buildParagraph(
        'Approve grants immediate access and sends them a welcome email. Waitlist leaves their access unchanged.',
      );
  } else {
    // Token/pageUrl unavailable (e.g. the approval secret is unset) — still send
    // the FYI so signups@ knows someone signed up, just without action buttons.
    body =
      buildParagraph('Someone just signed up for Liftoff. Review their details below.') + tableHtml;
  }

  const { html } = buildEmail('signup-notification', {
    firstName: '',
    rawHtml: body,
  });

  const fullName = `${account.firstName} ${account.lastName}`.trim();
  const who = fullName ? `${fullName} (${account.email})` : account.email;

  return sendEmail({
    to: notifyTo,
    subject: `New signup: ${sanitizeForEmail(who)}`,
    html,
    emailType: 'signup-notification',
    replyTo: account.email,
  });
}

