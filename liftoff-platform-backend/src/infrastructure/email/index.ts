// Email Service using Resend
// Liftoff wordmark is attached as a CID inline MIME part (Resend's
// `attachments[].content_id` field). The FOOTER references it via
// <img src="cid:logo">. CID attachments are embedded directly in
// the email payload — no remote fetch — and render in Gmail, Apple Mail,
// and Outlook even when "load remote images" is disabled. This replaces
// the prior inline-SVG approach which Outlook silently strips.

import { getResendApiKey } from '../secrets';
import { log } from '../logging';
import { buildEmail, buildParagraph, buildList, buildListIntro, buildCTA, buildOutlineButton, BuildOptions } from './builder';
import { escapeHtml } from './sanitize';
import { LIFTOFF_WORDMARK_PNG_BASE64 } from './logo-asset';
import { EMAIL_COLORS } from './shared';
import { mailFrom, mailReplyToAddress, signupNotificationAddress } from '../mail-identity';
import { frontendUrl } from '../frontend-url';

const RESEND_API_URL = 'https://api.resend.com/emails';

// The From / Reply-To addresses and the frontend's base URL belong to whoever
// runs this deployment, so all three are resolved per send rather than being
// constants here: mail-identity.ts for the addresses, frontend-url.ts for the
// links. An email provider only signs mail for a domain its own account has
// verified, so there is no From address that works by default.
//
// Read per call rather than at module load, for the reason frontend-url.ts
// gives: a value captured at import cannot be overridden by a test and cannot
// pick up configuration that arrives after the module graph is built.


interface SendEmailOptions {
  to: string;
  subject: string;
  html: string;
  emailType: string;
  replyTo?: string;
  // Overrides the From display NAME only; the address stays this deployment's
  // own so SPF/DKIM/DMARC alignment is unaffected. Used for
  // "{inviter} via Liftoff".
  fromName?: string;
  headers?: Record<string, string>;
}

interface ResendResponse {
  id: string;
}

export async function sendEmail(options: SendEmailOptions): Promise<string> {
  const apiKey = await getResendApiKey();

  // Custom From display name (e.g. "Paul Drummond via Liftoff"), quoted and
  // stripped of header-breaking characters by mailFrom(). The address stays
  // on-domain; an empty name falls back to MAIL_FROM_NAME.
  const from = mailFrom(options.fromName);

  const response = await fetch(RESEND_API_URL, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      from,
      reply_to: options.replyTo || mailReplyToAddress(),
      to: [options.to],
      subject: options.subject,
      html: options.html,
      tags: [
        { name: 'category', value: 'transactional' },
        { name: 'type', value: options.emailType },
      ],
      // Liftoff wordmark embedded as a CID inline attachment. The FOOTER
      // template references it via <img src="cid:logo">. Adds
      // ~3.3KB to each email payload (the base64-encoded PNG) which is
      // negligible vs the average HTML body size.
      attachments: [
        {
          filename: 'liftoff.png',
          content: LIFTOFF_WORDMARK_PNG_BASE64,
          content_id: 'logo',
          content_type: 'image/png',
        },
      ],
      ...(options.headers ? { headers: options.headers } : {}),
    }),
  });

  if (!response.ok) {
    const error = await response.text();
    log.error({ status: response.status, error, emailType: options.emailType }, 'Resend API error');
    throw new Error(`Resend API error: ${response.status} - ${error}`);
  }

  const result = await response.json() as ResendResponse;
  log.info({ emailId: result.id, emailType: options.emailType, to: options.to }, 'Email sent successfully');
  return result.id;
}

// [SE-008] Email Template Sanitization
function sanitizeForEmail(input: string): string {
  return input
    .replace(/[\r\n]/g, '')  // Remove CRLF injection
    .replace(/[<>]/g, '')     // Remove HTML tags
    .substring(0, 100);       // Enforce max length
}

