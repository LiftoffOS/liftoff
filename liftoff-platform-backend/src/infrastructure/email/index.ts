/**
 * Sent by the daily invite-expiry sweep (jobs/invite-expiry-sweep.ts) to an
 * inviter, aggregating every person they invited whose invitation has lapsed —
 * one email per inviter however many invitees expired, including several on the
 * same day. The invitee list is composed here with the builder list primitive
 * and passed to buildEmail as rawHtml.
 */
export async function sendInvitesExpiredEmail(
  to: string,
  inviterFirstName: string,
  params: {
    tenantName: string;
    inviteUrl: string;
    invitees: Array<{ email: string; invitedAt: Date }>;
  },
): Promise<string> {
  const safeTenantName = sanitizeForEmail(params.tenantName);
  const listItems = params.invitees.map((i) => {
    const email = escapeHtml(i.email);
    // Our own mailto anchor, styled to the body colour with no underline, so the
    // client renders the address as plain text instead of auto-detecting the raw
    // address and painting its own blue link over it.
    return `<a href="mailto:${email}" style="color:${EMAIL_COLORS.text};font-weight:400;text-decoration:none;">${email}</a> &middot; invited ${escapeHtml(formatLongDate(i.invitedAt))}`;
  });
  const rawHtml =
    buildParagraph(
      `The people you invited to your Liftoff workspace, <strong>${escapeHtml(params.tenantName)}</strong>, have not accepted your invitations. Invitations expire 7 days after they are sent.`,
    ) +
    buildListIntro('Not yet joined:') +
    buildList(listItems) +
    buildParagraph('To onboard them to your Liftoff workspace, send them a new invitation.');

  const { subject, html } = buildEmail('invites-expired', {
    firstName: sanitizeForEmail(inviterFirstName) || 'there',
    teamName: safeTenantName,
    inviteUrl: params.inviteUrl,
    rawHtml,
  });

  return sendEmail({ to, subject, html, emailType: 'invites-expired' });
}

/**
 * Sent by the reminder sweep (jobs/invite-reminder-sweep.ts) to the RECIPIENT
 * of a still-pending invitation, 2 to 3 days before it expires. inviteUrl
 * carries the reminder's OWN token; the original invitation link keeps working
 * too. The inviter's first/last name are NOT NULL but may be empty, so the
 * intro degrades gracefully: "First Last" -> whatever name we have -> a
 * name-free, workspace-only sentence. The recipient's own name is never used —
 * they are a non-user we have no name for.
 */
export async function sendInviteReminderEmail(
  to: string,
  params: {
    tenantName: string;
    inviteUrl: string;
    inviterFirstName: string;
    inviterLastName: string;
    inviterEmail: string;
    expiresAt: Date;
    inviterTimezone: string;
  },
): Promise<string> {
  const safeTenantName = sanitizeForEmail(params.tenantName);
  const display = `${(params.inviterFirstName || '').trim()} ${(params.inviterLastName || '').trim()}`.trim();
  const team = escapeHtml(params.tenantName);
  const intro = display
    ? `<strong>${escapeHtml(display)}</strong> invited you to join <strong>${team}</strong> on Liftoff, and your invitation has not been accepted yet.`
    : `You have been invited to join <strong>${team}</strong> on Liftoff, and your invitation has not been accepted yet.`;

  // Full month + day, in the inviter's zone (the workspace's frame, as the expiry
  // sweep uses). Never "in N days": a daily sweep fires anywhere in the window, so
  // a concrete date is the only always-accurate wording. An unrecognized zone
  // falls back to UTC rather than throwing.
  const expiryDate = formatExpiryDate(params.expiresAt, params.inviterTimezone);

  const { subject, html } = buildEmail('invite-reminder', {
    firstName: '',
    teamName: safeTenantName,
    inviteUrl: params.inviteUrl,
    expiryDate,
    rawHtml: buildParagraph(intro),
  });

  // A reply reaches the inviter, and the From reads "{inviter} via Liftoff",
  // matching the original invitation.
  return sendEmail({
    to,
    subject,
    html,
    emailType: 'invite-reminder',
    replyTo: params.inviterEmail,
    fromName: display ? `${display} via Liftoff` : undefined,
  });
}

/**
 * Sent by POST /api/referrals/invites to somebody a paying workspace wants to
 * recommend Liftoff to.
 *
 * The offer is stated in dollars on both sides, because the person reading this
 * has never used Liftoff and would have to learn what an Operating Unit is
 * before the offer meant anything. The grant itself is still Operating Units
 * and the sentence says so.
 *
 * `message` is the sender's own note and is the reason this endpoint is gated
 * at all: attacker-controlled prose inside Liftoff branding is what makes a
 * phishing wrapper effective. It arrives already reduced to a single run of
 * plain text by the service, and is escaped again here — the two are not
 * redundant, they are the sanitizer and the encoder, and only the second one
 * knows it is producing HTML.
 *
 * The From reads "{inviter} via Liftoff" where the referrer's name is known, the
 * same as a workspace invitation, because a person recommending something lands
 * better than a workspace name and the recipient deserves to know who it is.
 *
 * The reply-to is the one thing NOT copied from a workspace invitation. That
 * address never asked to hear from the sender, so routing replies to them would
 * hand a stranger's inbox to whoever paid for a subscription. Replies go to
 * support, and `routes replies nowhere near the sender` in the tests holds it
 * that way.
 */
export async function sendReferralInviteEmail(
  to: string,
  params: {
    workspaceName: string;
    /** The referrer's full name, where the account has one. Empty falls back
     *  to the workspace, which is all this email had before. */
    inviterName?: string;
    inviteUrl: string;
    message: string | null;
    refereeBonusUsd: number;
    refereeBonusOus: number;
  },
): Promise<string> {
  const fullName = (params.inviterName ?? '').trim();
  const fullWorkspace = (params.workspaceName ?? '').trim();
  const safeWorkspaceName = sanitizeForEmail(params.workspaceName);
  const safeInviterName = sanitizeForEmail(fullName);
  const workspace = escapeHtml(params.workspaceName);
  const person = escapeHtml(fullName);

  // The workspace is only worth naming when somebody chose it. Both defaults
  // (tenants/service.ts: 'Personal Workspace', or "{firstName}'s Workspace")
  // are machine-generated, and a workspace nobody renamed produces
  // "Alex Rivera at Alex's Workspace", which reads worse than saying
  // nothing. Anything the customer typed themselves is kept, including a name
  // that merely resembles a default, because the test is exact.
  const workspaceIsDefault = /^(personal workspace|.+'s workspace)$/i.test(fullWorkspace);

  // Who the subject line, heading and From name. The person where we have one,
  // since "Ada Lovelace invites you" reads as a recommendation and "Acme Ltd
  // invites you" reads as an advert. A default workspace name is not a name
  // anybody chose, so it is never used as the sender: an empty label here
  // switches the whole email to the unnamed variant rather than announcing
  // "Personal Workspace invites you to try Liftoff".
  const senderLabel = safeInviterName || (workspaceIsDefault ? '' : safeWorkspaceName);

  // Both, when we have both: the name makes it personal and the workspace is
  // what makes it credible.
  const attribution = person && !workspaceIsDefault
    ? `<strong>${person}</strong> at <strong>${workspace}</strong>`
    : person
      ? `<strong>${person}</strong>`
      : workspaceIsDefault
        ? ''
        : `<strong>${workspace}</strong>`;

  // With nobody to name, the sentence has to carry itself.
  const opening = attribution
    ? `${attribution} uses Liftoff to run an AI workforce, and recommends it to you. `
    : 'Someone using Liftoff to run an AI workforce recommends it to you. ';

  const offer = buildParagraph(
    `${opening}`
    + `Subscribe through their link and get a bonus `
    + `${params.refereeBonusOus.toLocaleString('en-US')} Operating Units ($${params.refereeBonusUsd} of usage) `
    + `in your first billing period.`,
  );
  const note = params.message
    ? buildParagraph(`They added: &ldquo;${escapeHtml(params.message)}&rdquo;`)
    : '';

  const { subject, html } = buildEmail(senderLabel ? 'referral-invite' : 'referral-invite-unnamed', {
    firstName: '',
    // The template's {teamName} slot is the sender's identity, not strictly the
    // workspace: it carries the person's name when there is one. The unnamed
    // variant does not interpolate it at all.
    teamName: senderLabel,
    inviteUrl: params.inviteUrl,
    refereeBonusUsd: `$${params.refereeBonusUsd}`,
    rawHtml: offer + note,
  });

  return sendEmail({
    to,
    subject,
    html,
    emailType: 'referral-invite',
    // Name only. No replyTo: see the note above. Falls back to the plain
    // "Liftoff" From when there is nobody to credit, rather than putting a
    // machine-generated workspace name in the sender.
    fromName: senderLabel ? `${senderLabel} via Liftoff` : undefined,
  });
}

function formatExpiryDate(expiresAt: Date, timeZone: string): string {
  const opts: Intl.DateTimeFormatOptions = { month: 'long', day: 'numeric' };
  try {
    return expiresAt.toLocaleDateString('en-US', { ...opts, timeZone: timeZone || 'UTC' });
  } catch {
    return expiresAt.toLocaleDateString('en-US', { ...opts, timeZone: 'UTC' });
  }
}

export async function sendPaymentFailedEmail(
  to: string,
  firstName: string,
  context: 'subscription_renewal' | 'auto_reload',
  params: {
    outstandingBalanceUsd?: number;
    amountUsd?: number;
    paymentMethodType?: 'card' | 'us_bank_account';
    paymentMethodLast4?: string;
  },
): Promise<string> {
  const templateKey =
    context === 'auto_reload' ? 'payment-failed-auto-reload' :
    'payment-failed-subscription';

  const buildOpts: BuildOptions = {
    firstName: firstName || 'there',
    frontendUrl: frontendUrl(),
  };
  if (params.outstandingBalanceUsd !== undefined) {
    buildOpts.outstandingBalanceUsd = `$${params.outstandingBalanceUsd.toFixed(2)}`;
  }
  if (params.amountUsd !== undefined) {
    buildOpts.amountUsd = params.amountUsd.toFixed(2);
  }
  if (context === 'auto_reload' && params.paymentMethodType && params.paymentMethodLast4) {
    buildOpts.paymentMethodSummary = params.paymentMethodType === 'card'
      ? `credit card ending in ${params.paymentMethodLast4}`
      : `bank account ending in ${params.paymentMethodLast4}`;
  }

  const { subject, html } = buildEmail(templateKey, buildOpts);
  return sendEmail({
    to,
    subject,
    html,
    emailType: templateKey,
  });
}

export async function sendSubscriptionConfirmationEmail(
  to: string,
  firstName: string,
  params: {
    planName: string;
    monthlyAllocationOus: number;
    planPriceUsd: number;
    billingPeriod: 'month' | 'year';
    nextRenewalDate: Date;
    promoApplied?: { amountOffUsd: number; firstInvoiceTotalUsd: number };
  },
): Promise<string> {
  // `nextRenewalDate` is accepted by the send-fn so the confirmation template
  // plumbing has it, but is intentionally NOT rendered into the current copy —
  // subscription-active emails never surface renewal dates (the renewal will
  // be reaffirmed in the recurring `receipt` email when it actually fires).
  void params.nextRenewalDate;
  const billingSummary = `$${params.planPriceUsd.toFixed(2)}/${params.billingPeriod}, ${params.monthlyAllocationOus.toLocaleString()} Operating Units included`;
  // Pre-compose the promo sentence here so the template only needs a flat
  // {promoSummary} placeholder. Empty string when no promo — the builder
  // substitution then renders nothing visible.
  const promoSummary = params.promoApplied
    ? (params.promoApplied.firstInvoiceTotalUsd === 0
      ? `Your promo code covered your first ${params.billingPeriod} — no charge today. `
      : `Your promo code took $${params.promoApplied.amountOffUsd.toFixed(2)} off your first invoice (paid: $${params.promoApplied.firstInvoiceTotalUsd.toFixed(2)}). `)
    : '';
  const { subject, html } = buildEmail('subscription-confirmation', {
    firstName: firstName || 'there',
    frontendUrl: frontendUrl(),
    planName: params.planName,
    billingSummary,
    promoSummary,
  });
  return sendEmail({ to, subject, html, emailType: 'subscription-confirmation' });
}

