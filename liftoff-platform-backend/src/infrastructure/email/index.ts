export async function sendReceiptEmail(
  to: string,
  firstName: string,
  context: 'subscription_renewal' | 'credit_reload',
  params: {
    amountUsd: number;
    paymentMethodType: 'card' | 'us_bank_account';
    paymentMethodLast4: string;
    planName?: string;
    billingPeriod?: 'month' | 'year';
  },
): Promise<string> {
  const paymentMethodSummary =
    params.paymentMethodType === 'card'
      ? `credit card ending in ${params.paymentMethodLast4}`
      : `bank account ending in ${params.paymentMethodLast4}`;
  const chargeReason =
    context === 'subscription_renewal'
      ? `renew your ${params.planName} plan for another ${params.billingPeriod}`
      : 'fund your Liftoff credit balance';
  const { subject, html } = buildEmail('receipt', {
    firstName: firstName || 'there',
    frontendUrl: frontendUrl(),
    amountUsd: params.amountUsd.toFixed(2),
    paymentMethodSummary,
    chargeReason,
  });
  return sendEmail({ to, subject, html, emailType: `receipt-${context}` });
}

export async function sendSubscriptionEndedEmail(
  to: string,
  firstName: string,
  params: { planName: string; accessEndedDate: Date },
): Promise<string> {
  const { subject, html } = buildEmail('subscription-ended', {
    firstName: firstName || 'there',
    frontendUrl: frontendUrl(),
    planName: params.planName,
    accessEndedDate: formatLongDate(params.accessEndedDate),
  });
  return sendEmail({ to, subject, html, emailType: 'subscription-ended' });
}

