// Internal-agent outbox API: transactional event enqueue + synchronous
// post-commit publish + background worker for the rare retry case.
//
// Pattern: see migration 203_internal_agent_outbox.sql + plan §5.2.
//
// Calling convention:
//
//   const rowRef = await withAdminScope(ctx, async (client) => {
//     await client.query(`UPDATE/INSERT/DELETE ... RETURNING *`);
//     return enqueueInternalAgentOutbox(client, { ... });
//   });
//   // Tx committed. Publish inline (never throws):
//   await publishOutboxRowInline(rowRef);
//   return res.status(201).json(entity);
//
// publishOutboxRowInline NEVER throws. On failure the row stays 'pending' and
// the worker (startInternalAgentOutboxWorker) drains within 30s. Runtime-side
// dedupe via event_processing_ledger keeps the retry safe even when inline
// publish succeeded but mark-completed failed.

import type { PoolClient } from 'pg';
import { publishEventWithExplicitId } from '../events/publisher';
import { withAdminScope } from '../infrastructure/database';
import { log } from '../infrastructure/logging';

// Event types that the internal_agent_outbox accepts. Adding a new entry here
// requires:
//   1. A matching handler in liftoff-tenant-runtime/src/events/subscriber.ts
//      (otherwise dispatch falls through to `default:` and the message is
//      acked with a warning — wasted bandwidth + log noise).
//   2. If state-mutating, the new event type added to the stale-after-delete
//      gate in subscriber.ts so it can't resurrect tombstoned agents.
//   3. The migration's CHECK constraint already allows
//      'tenant.internal_agent.%' so no new migration is needed.
//
// Currently handled by the runtime (see subscriber.ts dispatch + handlers):
//   created, updated, deleted, status_changed, runtime_config_updated, skills_updated
//
// Defined here but NOT currently handled — DO NOT publish without first
// wiring the handler. chat_started / chat_feedback_received are not
// published for this reason. Keep them in the union
// so a future analytics handler can reference the literal type without a
// type-only change to this file.
export type InternalAgentOutboxEventType =
  | 'tenant.internal_agent.created'
  | 'tenant.internal_agent.updated'
  | 'tenant.internal_agent.deleted'
  | 'tenant.internal_agent.status_changed'
  | 'tenant.internal_agent.runtime_config_updated'
  | 'tenant.internal_agent.skills_updated'
  // ↓ defined but not currently published or handled. See note above.
  | 'tenant.internal_agent.chat_started'
  | 'tenant.internal_agent.chat_feedback_received'
  | 'tenant.internal_agent.redist_recommended'
  | 'tenant.internal_agent.skills_backfilled';

export interface EnqueueOutboxInput {
  tenantId: string;
  internalAgentId: string;
  eventType: InternalAgentOutboxEventType;
  entityVersion: number | null;
  payload: Record<string, unknown>;
}

export interface OutboxRowRef {
  outboxId: string;
  eventId: string;
  tenantId: string;
  internalAgentId: string;
  eventType: InternalAgentOutboxEventType;
  entityVersion: number | null;
  payload: Record<string, unknown>;
}

const INLINE_PUBLISH_TIMEOUT_MS = 3000;
const REAPER_THRESHOLD_MIN = 5;

// Step 1: enqueue inside the caller's transaction. Returns the row ref so the
// caller can publish inline AFTER tx commit. The event_id is generated by the
// gen_random_uuid() DEFAULT — we read it back so inline publish + worker retry
// use the SAME id.
export async function enqueueInternalAgentOutbox(
  client: PoolClient,
  input: EnqueueOutboxInput,
): Promise<OutboxRowRef> {
  // Single-statement upsert that REWRITES the row on conflict.
  //
  // The partial unique index (status IN ('pending','in_progress')) collapses
  // concurrent enqueues for the same (tenant, agent, event_type) into one
  // outbox row. Two failure modes need handling:
  //
  //   1. DO NOTHING + follow-up SELECT (original): SELECT races with another
  //      tx's mark-completed between the INSERT and SELECT — returns 0 rows
  //      and crashes reading existing.rows[0].id.
  //
  //   2. DO UPDATE SET updated_at = updated_at (no-op): atomic, but for
  //      genuinely concurrent UPDATEs of the same agent (Tx A v=5 then Tx B
  //      v=6 while v=5 is still pending), Tx B's DO UPDATE returns Tx A's
  //      event_id. Tx B's inline publish then uses event_id_A which the
  //      runtime already deduped → Tx B's mutation never reaches the
  //      runtime, leaving silent v=6 drift until the 5-min reconciler.
  //
  // The correct semantics: on conflict OVERWRITE the row with the new
  // mutation's payload + entity_version, RESET event_id (so runtime dedupe
  // doesn't drop the second publish), RESET status/attempts (so a worker
  // mid-claim that's already in flight with the old event_id can complete
  // independently). The in-flight Tx A inline publish uses its in-memory
  // event_id_A; Tx B's publishes via the new event_id_B — both reach the
  // runtime, and the version gate orders them correctly.
  const result = await client.query<{ id: string; event_id: string }>(
    `INSERT INTO internal_agent_outbox
       (tenant_id, internal_agent_id, event_type, entity_version, event_payload)
     VALUES ($1, $2, $3, $4, $5::jsonb)
     ON CONFLICT (tenant_id, internal_agent_id, event_type)
       WHERE status IN ('pending', 'in_progress')
       DO UPDATE SET
         event_id        = gen_random_uuid(),
         event_payload   = EXCLUDED.event_payload,
         entity_version  = EXCLUDED.entity_version,
         status          = 'pending',
         attempts        = 0,
         last_error      = NULL,
         next_attempt_at = NOW(),
         updated_at      = NOW()
     RETURNING id, event_id`,
    [input.tenantId, input.internalAgentId, input.eventType, input.entityVersion, JSON.stringify(input.payload)],
  );

  if (result.rows.length === 0) {
    // Should never happen with DO UPDATE … RETURNING; defensive guard so we
    // surface the failure mode loudly if a future migration breaks the
    // partial unique index targeting.
    throw new Error('enqueueInternalAgentOutbox: upsert returned no rows');
  }

  return {
    outboxId: result.rows[0].id,
    eventId: result.rows[0].event_id,
    tenantId: input.tenantId,
    internalAgentId: input.internalAgentId,
    eventType: input.eventType,
    entityVersion: input.entityVersion,
    payload: input.payload,
  };
}

// Step 2: publish inline after caller's tx commit. NEVER throws.
export async function publishOutboxRowInline(row: OutboxRowRef): Promise<{ inlinePublished: boolean }> {
  try {
    await Promise.race([
      publishEventWithExplicitId({
        eventId: row.eventId,
        entityType: 'internal_agent',
        entityId: row.internalAgentId,
        eventType: row.eventType,
        entityVersion: row.entityVersion,
        eventVersion: 1,
        tenantId: row.tenantId,
        payload: row.payload,
      }),
      new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error('inline publish timed out after 3s')), INLINE_PUBLISH_TIMEOUT_MS),
      ),
    ]);
    await markCompleted(row.outboxId);
    return { inlinePublished: true };
  } catch (err) {
    log.warn(
      { outboxId: row.outboxId, eventId: row.eventId, err: (err as Error).message },
      'inline publish failed — leaving outbox row pending for worker',
    );
    await markRetryFromInline(row.outboxId, (err as Error).message).catch(() => { /* non-critical */ });
    return { inlinePublished: false };
  }
}

interface OutboxRow {
  id: string;
  tenant_id: string;
  internal_agent_id: string;
  event_id: string;
  event_type: InternalAgentOutboxEventType;
  event_payload: Record<string, unknown>;
  entity_version: number | null;
  attempts: number;
  max_attempts: number;
}

export async function runInternalAgentOutboxOnce(): Promise<void> {
  await reapStuckInProgress();
  for (let i = 0; i < 25; i++) {
    const row = await claimOne();
    if (!row) break;
    await processRow(row);
  }
}

async function reapStuckInProgress(): Promise<void> {
  await withAdminScope(
    { caller: 'internal-agent-outbox-worker.reaper', reason: 'reset stuck in_progress rows' },
    (c) => c.query(
      `UPDATE internal_agent_outbox
         SET status='pending', updated_at=NOW()
       WHERE status='in_progress'
         AND updated_at < NOW() - ($1::int * INTERVAL '1 minute')`,
      [REAPER_THRESHOLD_MIN],
    ),
  );
}

async function claimOne(): Promise<OutboxRow | null> {
  return withAdminScope(
    { caller: 'internal-agent-outbox-worker.claim', reason: 'claim one due row' },
    async (c) => {
      const r = await c.query<OutboxRow>(
        `UPDATE internal_agent_outbox
           SET status='in_progress', updated_at=NOW()
         WHERE id = (
           SELECT id FROM internal_agent_outbox
           WHERE status='pending' AND next_attempt_at <= NOW()
           ORDER BY next_attempt_at
           FOR UPDATE SKIP LOCKED LIMIT 1
         )
         RETURNING id, tenant_id, internal_agent_id, event_id, event_type,
                   event_payload, entity_version, attempts, max_attempts`,
      );
      return r.rows[0] ?? null;
    },
  );
}

async function processRow(row: OutboxRow): Promise<void> {
  try {
    await publishEventWithExplicitId({
      eventId: row.event_id,
      entityType: 'internal_agent',
      entityId: row.internal_agent_id,
      eventType: row.event_type,
      entityVersion: row.entity_version,
      eventVersion: 1,
      tenantId: row.tenant_id,
      payload: row.event_payload,
    });
    await markCompleted(row.id);
  } catch (err) {
    await markRetry(row.id, row.attempts + 1, row.max_attempts, (err as Error).message);
  }
}

async function markCompleted(id: string): Promise<void> {
  await withAdminScope(
    { caller: 'internal-agent-outbox.markCompleted', reason: 'mark outbox row completed' },
    (c) => c.query(
      `UPDATE internal_agent_outbox
         SET status='completed', completed_at=NOW(), updated_at=NOW()
       WHERE id=$1`,
      [id],
    ),
  );
}

async function markRetryFromInline(id: string, error: string): Promise<void> {
  await withAdminScope(
    { caller: 'internal-agent-outbox.markRetryFromInline', reason: 'inline publish failed' },
    (c) => c.query(
      `UPDATE internal_agent_outbox
         SET attempts = attempts + 1,
             last_error = $2,
             next_attempt_at = NOW() + (LEAST(10, POWER(2, attempts + 1))::int * INTERVAL '1 minute'),
             updated_at = NOW()
       WHERE id = $1`,
      [id, error],
    ),
  );
}

async function markRetry(
  id: string,
  attempts: number,
  maxAttempts: number,
  error: string,
): Promise<void> {
  const backoffMin = Math.min(10, 2 ** attempts);
  const terminal = attempts >= maxAttempts;
  await withAdminScope(
    { caller: 'internal-agent-outbox.markRetry', reason: terminal ? 'max attempts exceeded' : 'schedule retry' },
    (c) => c.query(
      terminal
        ? `UPDATE internal_agent_outbox
             SET status='failed', attempts=$2, last_error=$3, updated_at=NOW()
           WHERE id=$1`
        : `UPDATE internal_agent_outbox
             SET status='pending', attempts=$2, last_error=$3,
                 next_attempt_at = NOW() + ($4::int * INTERVAL '1 minute'),
                 updated_at = NOW()
           WHERE id=$1`,
      terminal ? [id, attempts, error] : [id, attempts, error, backoffMin],
    ),
  );
}

let workerInterval: NodeJS.Timeout | null = null;

// Bootstrap: 30s poll loop. Idempotent — calling twice does nothing.
export function startInternalAgentOutboxWorker(): void {
  if (workerInterval) return;
  workerInterval = setInterval(() => {
    runInternalAgentOutboxOnce().catch((err) =>
      log.error({ err: (err as Error).message }, 'internal-agent-outbox-worker tick failed'),
    );
  }, 30_000);
  workerInterval.unref();
  log.info('internal-agent-outbox-worker started (30s tick)');
}

export function stopInternalAgentOutboxWorker(): void {
  if (workerInterval) {
    clearInterval(workerInterval);
    workerInterval = null;
  }
}
