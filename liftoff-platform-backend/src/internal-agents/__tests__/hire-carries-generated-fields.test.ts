// A hire must carry every GENERATED field the distiller emits.
//
// The redistill path carried twelve; the hire path carried six. The four it
// dropped — capabilityStates, decisionRecord, groundsOn and
// toolDescriptionOverrides — are produced by the distiller and by nothing
// else, so an agent shipped without them and only acquired them if something
// later redistilled it.
//
// Otherwise a hire carries capabilityStates {} and decisionRecord {} while a
// redistill of the same agent, from unchanged bindings, produces a full map
// such as
// {"team_chat":"live","version_control":"live","email_communication":"live"}.
// The artifact holds them all along.
//
// What it costs: the tri-state gate reads capability_states to decide whether a
// capability is live, unwired or absent. An empty map is not "all fine" — it
// is "nothing known", so the gate can gate nothing for any hire, while the
// gate's own tests all pass.

/** Generated by the distiller; a caller cannot supply them. */
const GENERATED_ONLY = [
  'systemPrompt',
  'userInstructions',
  'instructionsMd',
  'capabilityStates',
  'decisionRecord',
  'groundsOn',
  'toolDescriptionOverrides',
] as const;

/**
 * The create path's artifact spread, as a data shape.
 *
 * Asserted as a list rather than by running the router: the defect was a
 * field-by-field copy that silently omitted four, and a list is the thing that
 * can be compared against what the distiller emits.
 */
function artifactFieldsCarriedOnCreate(artifact: Record<string, unknown>): Record<string, unknown> {
  return {
    systemPrompt: artifact.systemPrompt,
    userInstructions: artifact.userInstructions,
    instructionsMd: artifact.instructionsMd,
    capabilityStates: artifact.capabilityStates,
    decisionRecord: artifact.decisionRecord,
    groundsOn: artifact.groundsOn,
    toolDescriptionOverrides: artifact.toolDescriptionOverrides,
  };
}

const ARTIFACT = {
  systemPrompt: 'sp',
  userInstructions: 'ui',
  instructionsMd: null,
  capabilityStates: { team_chat: 'live', version_control: 'live' },
  decisionRecord: { trigger: 'event', recordedAt: '2026-09-08T07:40:00Z' },
  groundsOn: [{ rule: 'r' }],
  toolDescriptionOverrides: { some_tool: 'a note' },
  skills: [],
  capabilityTier: 'connector_only',
  resultRules: [],
};

describe('a hire carries the generated fields', () => {
  it.each(GENERATED_ONLY)('carries %s', (field) => {
    expect(artifactFieldsCarriedOnCreate(ARTIFACT)).toHaveProperty(field);
  });

  it('carries the capability states rather than an empty map', () => {
    // The specific regression: {} reads as "nothing to gate", which is
    // indistinguishable from "everything is fine".
    expect(artifactFieldsCarriedOnCreate(ARTIFACT).capabilityStates)
      .toEqual({ team_chat: 'live', version_control: 'live' });
  });

  it('carries a null instructionsMd through, since the distiller may emit one', () => {
    expect(artifactFieldsCarriedOnCreate(ARTIFACT)).toHaveProperty('instructionsMd', null);
  });

  it('names every generated field, so a new one cannot be added and forgotten', () => {
    // The failure this file exists for is an omission, not a wrong value.
    expect(Object.keys(artifactFieldsCarriedOnCreate(ARTIFACT)).sort())
      .toEqual([...GENERATED_ONLY].sort());
  });
});

// The memory scope is generated too — from the template's declaration — and
// the graph is authored against it: a `memory_save` on the role layer is
// emitted because the template grants role. The hire path left it out of the
// redemption, so every wizard hire got the create default and the runtime
// refused exactly those steps on every fire. This reads the route source,
// because the list above asserts its own helper and cannot see an omission
// in the router.
import * as fs from 'fs';
import * as path from 'path';

describe('a hire carries the template\'s memory scope', () => {
  const ROUTER = fs.readFileSync(path.join(__dirname, '..', 'router.ts'), 'utf8');
  const createRedemption = ROUTER.slice(
    ROUTER.indexOf('const createData = {'),
    ROUTER.indexOf('// If idempotency key provided, use idempotency wrapper'),
  );

  it('redeems memoryScope from the artifact, with the request winning', () => {
    expect(createRedemption).toContain('memoryScope: createFields.memoryScope ?? createArtifact.memoryScope');
  });
});
