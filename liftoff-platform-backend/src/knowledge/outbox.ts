// Knowledge outbox API: transactional event enqueue + synchronous post-commit
// publish + background worker for the rare retry case.
//
// Pattern: see migration 240_knowledge_outbox.sql + knowledge-ingestion
// event-driven plan §2.
//
// Calling convention:
//
//   const { items, outboxRefs } = await repo.batchCreate(tenantId, items);
//   // Tx committed. Publish inline (never throws):
//   await publishOutboxRefs(outboxRefs);
//
// publishOutboxRowInline NEVER throws. On failure the row stays 'pending' and
// the worker (startKnowledgeOutboxWorker) drains within 30s. Runtime-side
// dedupe via event_processing_ledger keeps the retry safe even when inline
// publish succeeded but mark-completed failed.

import type { PoolClient } from 'pg';
import { publishEventWithExplicitId } from '../events/publisher';
import { withAdminScope } from '../infrastructure/database';
import { log } from '../infrastructure/logging';

// Event types that the knowledge_outbox accepts. Adding a new entry here
// requires:
//   1. A matching handler case in src/events/subscriber.ts
//      handleControlPlaneEvent dispatch (otherwise dispatch falls through to
//      `default:` and the message is acked with a warning — wasted bandwidth +
//      log noise).
//   2. The migration's CHECK constraint already allows 'knowledge.%' so no new
//      migration is needed.
export type KnowledgeOutboxEventType =
  | 'knowledge.items.created';

export interface EnqueueOutboxInput {
  tenantId: string;
  itemId: string;
  eventType: KnowledgeOutboxEventType;
  entityVersion: number | null;
  payload: Record<string, unknown>;
}

export interface OutboxRowRef {
  outboxId: string;
  eventId: string;
  tenantId: string;
  itemId: string;
  eventType: KnowledgeOutboxEventType;
  entityVersion: number | null;
  payload: Record<string, unknown>;
}

const INLINE_PUBLISH_TIMEOUT_MS = 3000;
const REAPER_THRESHOLD_MIN = 5;

// Publish a batch of outbox rows with bounded concurrency. Each publish has a
// 3s inline timeout; running them serially in a tight loop would make a 500-doc
// bind wait minutes for the publish loop to finish before extraction even
// starts. CONCURRENCY=10 keeps Pub/Sub publish throughput high while bounding
// memory and avoiding burst-quota issues on the topic.
const INLINE_PUBLISH_CONCURRENCY = 10;
export async function publishOutboxRefs(refs: OutboxRowRef[]): Promise<void> {
  for (let i = 0; i < refs.length; i += INLINE_PUBLISH_CONCURRENCY) {
    const slice = refs.slice(i, i + INLINE_PUBLISH_CONCURRENCY);
    await Promise.all(slice.map(publishOutboxRowInline));
  }
}

// Step 1: enqueue inside the caller's transaction. Returns the row ref so the
// caller can publish inline AFTER tx commit. The event_id is generated by the
// gen_random_uuid() DEFAULT — we read it back so inline publish + worker retry
// use the SAME id.
export async function enqueueKnowledgeOutbox(
  client: PoolClient,
  input: EnqueueOutboxInput,
): Promise<OutboxRowRef> {
  // Single-statement upsert that REWRITES the row on conflict. See
  // internal-agents/outbox.ts enqueueInternalAgentOutbox for the full
  // explanation of why DO UPDATE (not DO NOTHING) is needed for correctness
  // under concurrent enqueue of the same (tenant, item, event_type).
  const result = await client.query<{ id: string; event_id: string }>(
    `INSERT INTO knowledge_outbox
       (tenant_id, item_id, event_type, entity_version, event_payload)
     VALUES ($1, $2, $3, $4, $5::jsonb)
     ON CONFLICT (tenant_id, item_id, event_type)
       WHERE status IN ('pending', 'in_progress')
       DO UPDATE SET
         event_id        = gen_random_uuid(),
         event_payload   = EXCLUDED.event_payload,
         entity_version  = EXCLUDED.entity_version,
         status          = 'pending',
         attempts        = 0,
         last_error      = NULL,
         next_attempt_at = NOW(),
         updated_at      = NOW()
     RETURNING id, event_id`,
    [input.tenantId, input.itemId, input.eventType, input.entityVersion, JSON.stringify(input.payload)],
  );

  if (result.rows.length === 0) {
    throw new Error('enqueueKnowledgeOutbox: upsert returned no rows');
  }

  return {
    outboxId: result.rows[0].id,
    eventId: result.rows[0].event_id,
    tenantId: input.tenantId,
    itemId: input.itemId,
    eventType: input.eventType,
    entityVersion: input.entityVersion,
    payload: input.payload,
  };
}

// Step 2: publish inline after caller's tx commit. NEVER throws.
export async function publishOutboxRowInline(row: OutboxRowRef): Promise<{ inlinePublished: boolean }> {
  try {
    await Promise.race([
      publishEventWithExplicitId({
        eventId: row.eventId,
        entityType: 'knowledge_item',
        entityId: row.itemId,
        eventType: row.eventType,
        entityVersion: row.entityVersion,
        eventVersion: 1,
        tenantId: row.tenantId,
        payload: row.payload,
      }),
      new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error('inline publish timed out after 3s')), INLINE_PUBLISH_TIMEOUT_MS),
      ),
    ]);
    await markCompleted(row.outboxId);
    return { inlinePublished: true };
  } catch (err) {
    log.warn(
      { outboxId: row.outboxId, eventId: row.eventId, err: (err as Error).message },
      'inline publish failed — leaving outbox row pending for worker',
    );
    await markRetryFromInline(row.outboxId, (err as Error).message).catch(() => { /* non-critical */ });
    return { inlinePublished: false };
  }
}

interface OutboxRow {
  id: string;
  tenant_id: string;
  item_id: string;
  event_id: string;
  event_type: KnowledgeOutboxEventType;
  event_payload: Record<string, unknown>;
  entity_version: number | null;
  attempts: number;
  max_attempts: number;
}

export async function runKnowledgeOutboxOnce(): Promise<void> {
  await reapStuckInProgress();
  for (let i = 0; i < 25; i++) {
    const row = await claimOne();
    if (!row) break;
    await processRow(row);
  }
}

async function reapStuckInProgress(): Promise<void> {
  await withAdminScope(
    { caller: 'knowledge-outbox-worker.reaper', reason: 'reset stuck in_progress rows' },
    (c) => c.query(
      `UPDATE knowledge_outbox
         SET status='pending', updated_at=NOW()
       WHERE status='in_progress'
         AND updated_at < NOW() - ($1::int * INTERVAL '1 minute')`,
      [REAPER_THRESHOLD_MIN],
    ),
  );
}

async function claimOne(): Promise<OutboxRow | null> {
  return withAdminScope(
    { caller: 'knowledge-outbox-worker.claim', reason: 'claim one due row' },
    async (c) => {
      const r = await c.query<OutboxRow>(
        `UPDATE knowledge_outbox
           SET status='in_progress', updated_at=NOW()
         WHERE id = (
           SELECT id FROM knowledge_outbox
           WHERE status='pending' AND next_attempt_at <= NOW()
           ORDER BY next_attempt_at
           FOR UPDATE SKIP LOCKED LIMIT 1
         )
         RETURNING id, tenant_id, item_id, event_id, event_type,
                   event_payload, entity_version, attempts, max_attempts`,
      );
      return r.rows[0] ?? null;
    },
  );
}

async function processRow(row: OutboxRow): Promise<void> {
  try {
    await publishEventWithExplicitId({
      eventId: row.event_id,
      entityType: 'knowledge_item',
      entityId: row.item_id,
      eventType: row.event_type,
      entityVersion: row.entity_version,
      eventVersion: 1,
      tenantId: row.tenant_id,
      payload: row.event_payload,
    });
    await markCompleted(row.id);
  } catch (err) {
    await markRetry(row.id, row.attempts + 1, row.max_attempts, (err as Error).message);
  }
}

async function markCompleted(id: string): Promise<void> {
  await withAdminScope(
    { caller: 'knowledge-outbox.markCompleted', reason: 'mark outbox row completed' },
    (c) => c.query(
      `UPDATE knowledge_outbox
         SET status='completed', completed_at=NOW(), updated_at=NOW()
       WHERE id=$1`,
      [id],
    ),
  );
}

async function markRetryFromInline(id: string, error: string): Promise<void> {
  await withAdminScope(
    { caller: 'knowledge-outbox.markRetryFromInline', reason: 'inline publish failed' },
    (c) => c.query(
      `UPDATE knowledge_outbox
         SET attempts = attempts + 1,
             last_error = $2,
             next_attempt_at = NOW() + (LEAST(10, POWER(2, attempts + 1))::int * INTERVAL '1 minute'),
             updated_at = NOW()
       WHERE id = $1`,
      [id, error],
    ),
  );
}

async function markRetry(
  id: string,
  attempts: number,
  maxAttempts: number,
  error: string,
): Promise<void> {
  const backoffMin = Math.min(10, 2 ** attempts);
  const terminal = attempts >= maxAttempts;
  await withAdminScope(
    { caller: 'knowledge-outbox.markRetry', reason: terminal ? 'max attempts exceeded' : 'schedule retry' },
    (c) => c.query(
      terminal
        ? `UPDATE knowledge_outbox
             SET status='failed', attempts=$2, last_error=$3, updated_at=NOW()
           WHERE id=$1`
        : `UPDATE knowledge_outbox
             SET status='pending', attempts=$2, last_error=$3,
                 next_attempt_at = NOW() + ($4::int * INTERVAL '1 minute'),
                 updated_at = NOW()
           WHERE id=$1`,
      terminal ? [id, attempts, error] : [id, attempts, error, backoffMin],
    ),
  );
}

let workerInterval: NodeJS.Timeout | null = null;

// Bootstrap: 30s poll loop. Idempotent — calling twice does nothing.
export function startKnowledgeOutboxWorker(): void {
  if (workerInterval) return;
  workerInterval = setInterval(() => {
    runKnowledgeOutboxOnce().catch((err) =>
      log.error({ err: (err as Error).message }, 'knowledge-outbox-worker tick failed'),
    );
  }, 30_000);
  workerInterval.unref();
  log.info('knowledge-outbox-worker started (30s tick)');
}

export function stopKnowledgeOutboxWorker(): void {
  if (workerInterval) {
    clearInterval(workerInterval);
    workerInterval = null;
  }
}
