#!/usr/bin/env npx ts-node
/**
 * Regenerates src/schemas/index.ts and src/overlays/index.ts from the per-toolkit
 * files present. Run after scaffolding a connector so index registration can't be
 * hand-mistyped across ~90 connectors.
 *
 * Convention (must hold): each src/schemas/<slug>.ts exports <SLUG>_SCHEMAS;
 * each src/overlays/<slug>.ts exports <SLUG>_OVERLAYS and <SLUG>_HISTORY_MAPPINGS.
 * The file name IS the canonical Composio toolkit slug (= connectors.ts
 * mcp.toolkitSlug). COMPOSIO_TOOL_* are keyed by slug; COMPOSIO_HISTORY_MAPPINGS
 * is keyed by Liftoff connector_type (inverse of COMPOSIO_TOOLKIT_SLUG_BY_TYPE).
 */

import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COMPOSIO_TOOLKIT_SLUG_BY_TYPE } from '../src/toolkit-slugs';

const SRC = resolve(__dirname, '../src');
const CONST = (s: string) => s.toUpperCase().replace(/[^A-Z0-9_]/g, '_');
const slugsIn = (dir: string) =>
  readdirSync(resolve(SRC, dir)).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort();

// slug -> [connector_type,...]
const typesBySlug: Record<string, string[]> = {};
for (const [type, slug] of Object.entries(COMPOSIO_TOOLKIT_SLUG_BY_TYPE)) (typesBySlug[slug] ??= []).push(type);

// ---- schemas/index.ts ----
const sSlugs = slugsIn('schemas');
const sImports = sSlugs.map((s) => `import { ${CONST(s)}_SCHEMAS } from './${s}';`).join('\n');
const sEntries = sSlugs.map((s) => `  ${s}: ${CONST(s)}_SCHEMAS,`).join('\n');
writeFileSync(resolve(SRC, 'schemas/index.ts'),
`// AUTO-GENERATED by scripts/build-indexes.ts. Do not edit by hand.

import type { ComposioVendorSchema } from '../types';
${sImports}

export const COMPOSIO_TOOL_SCHEMAS: Record<string, ComposioVendorSchema[]> = {
${sEntries}
};
`, 'utf8');

// ---- overlays/index.ts ----
const oSlugs = slugsIn('overlays');
const oImports = oSlugs.map((s) => `import { ${CONST(s)}_OVERLAYS, ${CONST(s)}_HISTORY_MAPPINGS } from './${s}';`).join('\n');
const oEntries = oSlugs.map((s) => `  ${s}: ${CONST(s)}_OVERLAYS,`).join('\n');
const hEntries: string[] = [];
for (const s of oSlugs) for (const type of (typesBySlug[s] ?? [])) hEntries.push(`  ${type}: ${CONST(s)}_HISTORY_MAPPINGS,`);
hEntries.sort();
const missing = oSlugs.filter((s) => !typesBySlug[s]);
if (missing.length) console.error(`WARN: overlay files with no connector_type in toolkit-slugs.ts (no history key): ${missing.join(', ')}`);
writeFileSync(resolve(SRC, 'overlays/index.ts'),
`// AUTO-GENERATED by scripts/build-indexes.ts. Do not edit by hand.

import type { ComposioToolOverlay, HistoryToolMapping } from '../types';
${oImports}

export const COMPOSIO_TOOL_OVERLAYS: Record<string, Record<string, ComposioToolOverlay>> = {
${oEntries}
};

export const COMPOSIO_HISTORY_MAPPINGS: Record<string, HistoryToolMapping[]> = {
${hEntries.join('\n')}
};
`, 'utf8');

console.error(`indexes rebuilt: ${sSlugs.length} schema, ${oSlugs.length} overlay toolkits.`);
