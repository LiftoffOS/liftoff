#!/usr/bin/env npx ts-node
/**
 * Regenerates packages/composio-overlays/src/schemas/<toolkit>.ts files
 * from the Composio API. Run manually before a release; CI does NOT
 * auto-regen because Composio occasionally renames tools and we want a
 * human-reviewed diff.
 *
 * Usage:  npm run sync:schemas
 * Env:    COMPOSIO_API_KEY (read from .env or Secret Manager
 *         composio-api-key in YOUR_GCP_PROJECT)
 *
 * Output: one src/schemas/<toolkit>.ts per composio_managed toolkit slug
 *         + the src/schemas/index.ts aggregator. Stable sort for clean PR
 *         diffs.
 *
 * Discovery: the canonical list of composio_managed toolkit slugs lives
 * in connector-service's CONNECTORS map at
 * liftoff-connector-service/src/catalog/connectors.ts. Until the
 * @liftoffos/connector-types package exposes a helper that re-exports
 * that set, this script falls back to a hard-coded list mirrored from
 * Liftoff-Tenant-Runtime/src/billing/composio-call-reporter.ts:25 (the
 * platform-side authoritative copy). If you add or remove a
 * composio_managed connector in CONNECTORS, update both copies.
 */

import { Composio } from '@composio/core';
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { SecretManagerServiceClient } from '@google-cloud/secret-manager';
import type { ComposioVendorSchema } from '../src/types';
import { COMPOSIO_TOOLKIT_SLUG_BY_TYPE } from '../src/toolkit-slugs';

const SCHEMAS_DIR = resolve(__dirname, '../src/schemas');
const FIXTURES_DIR = resolve(__dirname, '../src/__tests__/translations/fixtures');

// Toolkit slugs to sync, DERIVED from the single source of truth
// (toolkit-slugs.ts → COMPOSIO_TOOLKIT_SLUG_BY_TYPE, which mirrors
// connectors.ts mcp.toolkitSlug). Deriving instead of duplicating a
// hand-maintained list is deliberate: a duplicated list is exactly what
// drifted (cal_com/google_ads/microsoft_dynamics/atlassian_* pointed at
// toolkit slugs Composio does not serve → getRawComposioTools returned 0 →
// the seed schemas ended up hand-authored with GUESSED slugs that 404 at
// dispatch). One source of truth = the slug used to fetch is the slug used
// to dispatch. Add a new composio_managed connector once, in toolkit-slugs.ts.
const COMPOSIO_TOOLKIT_SLUGS: string[] = [
  ...new Set(Object.values(COMPOSIO_TOOLKIT_SLUG_BY_TYPE)),
].sort();

async function loadApiKey(): Promise<string> {
  if (process.env.COMPOSIO_API_KEY) return process.env.COMPOSIO_API_KEY;
  const env = (process.env.ENVIRONMENT ?? 'dev') as 'dev' | 'prod';
  const client = new SecretManagerServiceClient();
  const [resp] = await client.accessSecretVersion({
    name: `projects/YOUR_GCP_PROJECT/secrets/composio-api-key/versions/latest`,
  });
  const payload = resp.payload?.data?.toString();
  if (!payload) throw new Error('composio-api-key secret is empty');
  return payload;
}

/** Infer Liftoff categories from the vendor tool's name. Plan C1 step 3. */
function inferCategories(slug: string): ComposioVendorSchema['categories'] {
  const upper = slug.toUpperCase();
  if (/DELETE_|REMOVE_|ARCHIVE_|DESTROY_/.test(upper)) return ['write', 'destructive'];
  if (/SEND_.*EMAIL|POST_MESSAGE|SENDS_.*MESSAGE|CREATE_.*CALL|REPLY/.test(upper)) return ['write', 'outbound'];
  if (/SEND_|POST_|CREATE_|UPDATE_|MODIFY_|MERGE_/.test(upper)) return ['write'];
  if (/LIST_|GET_|FETCH_|SEARCH_|READ_/.test(upper)) return ['read'];
  return ['read'];
}

interface SdkTool {
  slug: string;
  name: string;
  description?: string;
  inputParameters?: {
    type: 'object';
    properties: Record<string, unknown>;
    required?: string[];
    title?: string;
    additionalProperties?: boolean;
  };
}

function normalize(t: SdkTool): ComposioVendorSchema {
  return {
    slug: t.slug,
    name: t.name,
    description: t.description ?? '',
    inputSchema: t.inputParameters ?? { type: 'object' as const, properties: {} },
    categories: inferCategories(t.slug),
  };
}

function renderToolkitFile(slug: string, schemas: ComposioVendorSchema[]): string {
  return `// AUTO-GENERATED by scripts/sync-schemas.ts.
// DO NOT EDIT BY HAND. Run \`npm run sync:schemas\` to regenerate.
//
// Toolkit: ${slug}
// Tool count: ${schemas.length}

import type { ComposioVendorSchema } from '../types';

export const ${slug.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}_SCHEMAS: ComposioVendorSchema[] = ${JSON.stringify(schemas, null, 2)};
`;
}

function renderIndex(slugs: string[]): string {
  const imports = slugs
    .map((s) => `import { ${s.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}_SCHEMAS } from './${s}';`)
    .join('\n');
  const entries = slugs
    .map((s) => `  ${s}: ${s.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}_SCHEMAS,`)
    .join('\n');
  return `// AUTO-GENERATED by scripts/sync-schemas.ts.

import type { ComposioVendorSchema } from '../types';
${imports}

export const COMPOSIO_TOOL_SCHEMAS: Record<string, ComposioVendorSchema[]> = {
${entries}
};
`;
}

async function main(): Promise<void> {
  const composio = new Composio({ apiKey: await loadApiKey() });
  const writtenSlugs: string[] = [];

  for (const slug of COMPOSIO_TOOLKIT_SLUGS.sort()) {
    try {
      const tools = (await composio.tools.getRawComposioTools({
        toolkits: [slug],
        limit: 500,
      })) as SdkTool[];
      const normalized = tools.map(normalize).sort((a, b) => a.slug.localeCompare(b.slug));
      writeFileSync(resolve(SCHEMAS_DIR, `${slug}.ts`), renderToolkitFile(slug, normalized), 'utf8');
      writtenSlugs.push(slug);

      // Fixture co-generation (plan C1 step 5): emit one .input.json per
      // vendor tool, constructed deterministically from the JSON Schema's
      // example values where present, else default-typed placeholders.
      // Translation tests pick these up; a fixture file that already
      // exists is preserved (operator-curated) — we only fill in the gaps.
      const fxToolkitDir = resolve(FIXTURES_DIR, slug);
      if (!existsSync(fxToolkitDir)) mkdirSync(fxToolkitDir, { recursive: true });
      for (const tool of normalized) {
        const fxPath = resolve(fxToolkitDir, `${tool.slug}.input.json`);
        if (!existsSync(fxPath)) {
          writeFileSync(fxPath, JSON.stringify(synthesizeInput(tool), null, 2) + '\n', 'utf8');
        }
      }

       
      console.error(`  ${slug}: ${normalized.length} tools`);
    } catch (e) {
       
      console.error(`  ${slug}: SKIPPED (${(e as Error).message})`);
    }
  }

  writeFileSync(resolve(SCHEMAS_DIR, 'index.ts'), renderIndex(writtenSlugs), 'utf8');
   
  console.error(`\nWrote ${writtenSlugs.length} toolkit schema files + index.`);
}

/** Synthesize a plausible input fixture from a Composio tool's JSON Schema.
 *  Tries to fill required fields first; uses sensible defaults per JSON
 *  Schema type. Translation tests can then replace these with curated
 *  values when they need vendor-realistic shapes. */
function synthesizeInput(tool: ComposioVendorSchema): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  const props = (tool.inputSchema.properties ?? {}) as Record<string, { type?: string; examples?: unknown[]; default?: unknown }>;
  const required = tool.inputSchema.required ?? [];
  for (const key of required) {
    const def = props[key];
    if (!def) { out[key] = ''; continue; }
    if (def.default !== undefined) { out[key] = def.default; continue; }
    if (Array.isArray(def.examples) && def.examples.length > 0) { out[key] = def.examples[0]; continue; }
    switch (def.type) {
      case 'string':  out[key] = `example-${key}`; break;
      case 'integer':
      case 'number':  out[key] = 1; break;
      case 'boolean': out[key] = false; break;
      case 'array':   out[key] = []; break;
      case 'object':  out[key] = {}; break;
      default:        out[key] = '';
    }
  }
  return out;
}

if (require.main === module) {
  main().catch((e) => {
     
    console.error(`Fatal: ${(e as Error).message}`);
    process.exit(1);
  });
}
