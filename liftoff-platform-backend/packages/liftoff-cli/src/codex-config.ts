// Codex profile + local model catalog generation.
//
// Writes ~/.codex/liftoff.config.toml — a DEDICATED profile launched with
// `codex --profile liftoff`. The user's default Codex/ChatGPT configuration
// (~/.codex/config.toml) is NEVER touched. An existing Liftoff profile is
// backed up before changes; setup is idempotent; the generated TOML and
// catalog are validated before success is reported.

import fs from 'fs';
import path from 'path';
import os from 'os';
import { execFileSync } from 'child_process';

export function codexDir(): string {
  return path.join(os.homedir(), '.codex');
}

export function liftoffProfilePath(): string {
  return path.join(codexDir(), 'liftoff.config.toml');
}

export function catalogPath(): string {
  return path.join(os.homedir(), '.liftoff', 'codex-models.json');
}

// ---------------------------------------------------------------------------
// Installed Codex version (compatibility diagnostics)
// ---------------------------------------------------------------------------

export function detectCodexVersion(): string | null {
  try {
    const out = execFileSync('codex', ['--version'], { encoding: 'utf-8', timeout: 10_000 }).trim();
    const match = out.match(/(\d+\.\d+\.\d+)/);
    return match ? match[1] : out || null;
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------------------
// Local model catalog
// ---------------------------------------------------------------------------

export interface CatalogModel {
  id: string;
  /** Reviewed capability/presentation metadata served by the proxy's
   *  /codex/v1/models endpoint (vendor-config model_catalog, migration 014).
   *  Copied VERBATIM — the CLI never invents capability values;
   *  the format is frozen against captured fixtures per supported Codex
   *  version in Phase 1. */
  metadata?: Record<string, unknown>;
}

/**
 * Write the version-compatible local catalog consumed via model_catalog_json.
 * Models come from the proxy's /codex/v1/models endpoint (already filtered to
 * Liftoff-approved AND priced models), including their reviewed metadata.
 */
export function writeModelCatalog(models: CatalogModel[], codexVersion: string | null): string {
  const file = catalogPath();
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const catalog = {
    schema_version: 1,
    generated_by: 'liftoff-cli',
    codex_version: codexVersion,
    models: models.map((m) => ({
      id: m.id,
      ...(m.metadata ?? {}),
    })),
  };
  fs.writeFileSync(file, JSON.stringify(catalog, null, 2) + '\n', { mode: 0o600 });
  return file;
}

export function validateCatalog(file: string): void {
  const parsed = JSON.parse(fs.readFileSync(file, 'utf-8')) as { models?: unknown[] };
  if (!Array.isArray(parsed.models) || parsed.models.length === 0) {
    throw new Error('Generated model catalog has no models');
  }
}

// ---------------------------------------------------------------------------
// Profile TOML
// ---------------------------------------------------------------------------

export interface CodexProfileInput {
  /** Environment-specific proxy base URL from the authenticated setup
   *  response (e.g. https://api-dev.example.com/proxy). Never synthesized. */
  proxyBaseUrl: string;
  defaultModel: string;
  catalogFile: string;
  helperPath: string;
}

const PROD_PROXY_BASE = 'https://api.example.com/proxy';

export function renderProfileToml(input: CodexProfileInput): string {
  const baseUrl = `${input.proxyBaseUrl.replace(/\/$/, '')}/codex/v1`;
  return `# Generated by @liftoffos/cli codex setup — do not edit by hand.
# This profile routes Codex through Liftoff using YOUR OpenAI Platform API
# key (never your ChatGPT subscription). Launch with: codex --profile liftoff

model = "${input.defaultModel}"
model_provider = "liftoff"
model_catalog_json = "${input.catalogFile}"

[model_providers.liftoff]
name = "Liftoff OpenAI Proxy"
base_url = "${baseUrl}"
wire_api = "responses"
supports_websockets = false

[model_providers.liftoff.auth]
command = "${input.helperPath}"
args = ["codex"]
timeout_ms = 5000
refresh_interval_ms = 0
`;
}

/** Minimal TOML validation: balanced tables, key=value lines, required keys. */
export function validateProfileToml(content: string): void {
  const required = [
    'model_provider = "liftoff"',
    'wire_api = "responses"',
    'supports_websockets = false',
    '[model_providers.liftoff]',
    '[model_providers.liftoff.auth]',
  ];
  for (const needle of required) {
    if (!content.includes(needle)) throw new Error(`Generated profile missing: ${needle}`);
  }
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    if (trimmed.startsWith('[') && trimmed.endsWith(']')) continue;
    if (!/^[A-Za-z_]+ = /.test(trimmed)) throw new Error(`Invalid TOML line: ${trimmed}`);
  }
}

export interface WriteProfileOptions {
  input: CodexProfileInput;
  environment?: 'dev' | 'prod' | string;
}

/**
 * Write the dedicated Liftoff profile:
 *   - NEVER touches the default Codex profile (~/.codex/config.toml).
 *   - Backs up an existing Liftoff profile to .bak before changing it.
 *   - Idempotent: identical content is not rewritten (and not re-backed-up).
 *   - Rejects a dev-to-prod mismatch: a non-prod environment must not point
 *     at the production proxy URL.
 */
export function writeLiftoffProfile(opts: WriteProfileOptions): { path: string; changed: boolean } {
  const { input, environment } = opts;
  if (environment && environment !== 'prod' && input.proxyBaseUrl.replace(/\/$/, '') === PROD_PROXY_BASE) {
    throw new Error(
      `Refusing to write a ${environment} profile pointing at the production proxy URL`,
    );
  }

  const content = renderProfileToml(input);
  validateProfileToml(content);

  const file = liftoffProfilePath();
  fs.mkdirSync(codexDir(), { recursive: true });

  let existing: string | null = null;
  try {
    existing = fs.readFileSync(file, 'utf-8');
  } catch {
    // no existing profile
  }

  if (existing === content) return { path: file, changed: false };
  if (existing !== null) {
    fs.copyFileSync(file, `${file}.bak`);
  }
  fs.writeFileSync(file, content, { mode: 0o600 });
  return { path: file, changed: true };
}

/** Remove ONLY Liftoff-managed Codex material. */
export function removeLiftoffProfile(): void {
  for (const f of [liftoffProfilePath(), `${liftoffProfilePath()}.bak`, catalogPath()]) {
    try {
      fs.unlinkSync(f);
    } catch {
      // absent — fine
    }
  }
}
