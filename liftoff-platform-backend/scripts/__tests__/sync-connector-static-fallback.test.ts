// Unit tests for the pure functions in the sync script. Live-fetch
// behavior is covered separately by the CI drift-check step, which runs
// the full CLI against the dev catalog endpoint.

import {
  deriveFunctionalTypes,
  deriveCapabilities,
  renderFile,
  STATIC_ONLY_CAPABILITIES,
  type CatalogResponse,
} from '../sync-connector-static-fallback';

describe('deriveFunctionalTypes', () => {
  it('returns only connectors with status=available, sorted', () => {
    const catalog: CatalogResponse = {
      version: 'v1',
      categoryLabels: {},
      connectors: [
        { type: 'zoom', status: 'available' },
        { type: 'github', status: 'available' },
        { type: 'quickbooks', status: 'coming_soon' },
        { type: 'notion', status: 'available' },
        { type: 'legacy_foo', status: 'deprecated' },
      ],
    };
    expect(deriveFunctionalTypes(catalog)).toEqual(['github', 'notion', 'zoom']);
  });

  it('returns [] for empty catalog', () => {
    expect(deriveFunctionalTypes({ version: 'v1', categoryLabels: {}, connectors: [] })).toEqual([]);
  });
});

describe('deriveCapabilities', () => {
  it('groups available-connector capabilities and merges static-only entries', () => {
    const catalog: CatalogResponse = {
      version: 'v1',
      categoryLabels: {},
      connectors: [
        {
          type: 'salesforce',
          status: 'available',
          capabilities: [{ capability: 'crm', requiredScopes: ['api', 'refresh_token'] }],
        },
        {
          type: 'hubspot',
          status: 'available',
          capabilities: [
            { capability: 'crm', requiredScopes: ['crm.objects.contacts.read'] },
            { capability: 'email_marketing', requiredScopes: ['marketing-email:read'] },
          ],
        },
        {
          type: 'quickbooks',
          status: 'coming_soon',
          capabilities: [{ capability: 'accounting', requiredScopes: ['quickbooks.accounting'] }],
        },
      ],
    };

    const derived = deriveCapabilities(catalog);

    // CRM from two available connectors, sorted alphabetically by connectorType.
    expect(derived.crm).toEqual([
      { connectorType: 'hubspot', requiredScopes: ['crm.objects.contacts.read'] },
      { connectorType: 'salesforce', requiredScopes: ['api', 'refresh_token'] },
    ]);

    // quickbooks here is coming_soon, so the live catalog contributes
    // nothing to `accounting`; the result is just the STATIC_ONLY xero
    // entry.
    expect(derived.accounting).toEqual(STATIC_ONLY_CAPABILITIES.accounting);

    // email_marketing from hubspot + STATIC_ONLY merges (none for this cap).
    expect(derived.email_marketing).toEqual([
      { connectorType: 'hubspot', requiredScopes: ['marketing-email:read'] },
    ]);

    // STATIC_ONLY_CAPABILITIES.ats merges in (greenhouse + lever).
    expect(derived.ats).toEqual(STATIC_ONLY_CAPABILITIES.ats);
  });

  it('preserves STATIC_ONLY entries when no live connector provides the capability', () => {
    const derived = deriveCapabilities({ version: 'v1', categoryLabels: {}, connectors: [] });
    expect(derived.ats).toEqual(STATIC_ONLY_CAPABILITIES.ats);
  });

  it('returns keys in sorted order for deterministic git diff', () => {
    const catalog: CatalogResponse = {
      version: 'v1',
      categoryLabels: {},
      connectors: [
        { type: 'x', status: 'available', capabilities: [{ capability: 'zebra', requiredScopes: [] }] },
        { type: 'y', status: 'available', capabilities: [{ capability: 'alpha', requiredScopes: [] }] },
      ],
    };
    const keys = Object.keys(deriveCapabilities(catalog));
    expect(keys).toEqual([...keys].sort());
  });
});

describe('renderFile', () => {
  it('produces a deterministic TS file with AUTO-GENERATED marker + catalog version', () => {
    const output = renderFile(
      ['github', 'slack'],
      {
        crm: [{ connectorType: 'salesforce', requiredScopes: ['api'] }],
      },
      'v42abc',
    );

    expect(output).toContain('// AUTO-GENERATED by scripts/sync-connector-static-fallback.ts.');
    expect(output).toContain('// DO NOT EDIT BY HAND.');
    expect(output).toContain('Catalog version at generation: v42abc');
    expect(output).toContain('export const STATIC_CONNECTOR_CAPABILITIES');
    expect(output).toContain('export const STATIC_FUNCTIONAL_CONNECTOR_TYPES');
    expect(output).toContain('"salesforce"');
    expect(output).toContain('"github"');
    expect(output).toContain('"slack"');
  });

  it('is byte-stable across identical inputs (for git diff --exit-code)', () => {
    const inputs = {
      functional: ['github'],
      capabilities: { crm: [{ connectorType: 'salesforce', requiredScopes: ['api'] }] },
      version: 'v1',
    };
    const a = renderFile(inputs.functional, inputs.capabilities, inputs.version);
    const b = renderFile(inputs.functional, inputs.capabilities, inputs.version);
    expect(a).toBe(b);
  });
});
